// Command gen-sources regenerates specs/SOURCES.md, the provenance record for
// the vendored Figma OpenAPI spec. It is invoked by `make specs` right after the
// spec is pulled (never run by hand): it reads the fetched spec for its version,
// OpenAPI version, and operationId count, and writes SOURCES.md next to it.
//
// Usage: go run ./scripts/gen-sources <spec-file> <spec-url>
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen-sources <spec-file> <spec-url>")
		os.Exit(2)
	}
	specPath, url := os.Args[1], os.Args[2]

	spec, err := os.ReadFile(specPath)
	if err != nil {
		fatal(err)
	}
	version, openapi, ops := scan(string(spec))
	name := filepath.Base(specPath)
	date := time.Now().UTC().Format("2006-01-02")

	doc := fmt.Sprintf(`# Spec sources

Generated by `+"`make specs`"+` — do not edit by hand.

`+"`%s`"+` is Figma's published OpenAPI specification for the REST API — the
source of truth for every endpoint, parameter, and error shape the CLI knows
about. The embedded operation catalog
(`+"`internal/figmaapi/catalog/figma-catalog.json`"+`) is distilled from it by
`+"`scripts/build-catalog`"+`; never hand-edit that JSON.

| File | Source URL | Retrieved |
|------|------------|-----------|
| `+"`%s`"+` | %s | %s |

Refresh with `+"`make specs`"+` (re-pulls the spec and rewrites this file), then
`+"`make catalog`"+` to regenerate the embedded catalog; commit both. CI fails if
the committed catalog is not current with the spec.

Spec version at capture: Figma API v%s (OpenAPI %s), %d operationIds.
`, name, name, url, date, version, openapi, ops)

	out := filepath.Join(filepath.Dir(specPath), "SOURCES.md")
	if err := os.WriteFile(out, []byte(doc), 0o644); err != nil {
		fatal(err)
	}
	fmt.Println("SOURCES.md regenerated")
}

// scan pulls the top-level openapi version, the info.version, and the number of
// operationIds from the raw spec with a light line walk — enough provenance
// without unmarshaling the whole document.
func scan(spec string) (version, openapi string, ops int) {
	inInfo := false
	sc := bufio.NewScanner(strings.NewReader(spec))
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for sc.Scan() {
		line := sc.Text()
		switch {
		case strings.HasPrefix(line, "openapi:"):
			openapi = strings.TrimSpace(strings.TrimPrefix(line, "openapi:"))
		case strings.HasPrefix(line, "info:"):
			inInfo = true
		case inInfo && strings.HasPrefix(line, "  version:"):
			version = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "version:"))
			inInfo = false
		case strings.Contains(line, "operationId:"):
			ops++
		}
	}
	return version, openapi, ops
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen-sources:", err)
	os.Exit(1)
}
